package noxrender

import (
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"os"
	"testing"

	noxcolor "github.com/opennox/libs/color"
)

type originalMaterialRow struct {
	Index   int
	Input   [3]int
	RGB     *[3]int
	Color32 uint32
}

type originalRGB555Oracle struct {
	Original string `json:"original_sha256"`
	Mode     struct {
		Index, Pack, Unpack int
		MasksAndShifts      []uint32 `json:"masks_and_shifts"`
	}
	Split struct {
		Count     int
		RGBSHA256 string `json:"rgb_sha256"`
	}
	Materials    []originalMaterialRow
	RGBMaterials []originalMaterialRow `json:"rgb_materials"`
	MemoryFaults []json.RawMessage     `json:"memory_faults"`
	Unchanged    bool                  `json:"executable_and_table_unchanged"`
}

func readOriginalRGB555Oracle(t *testing.T) originalRGB555Oracle {
	t.Helper()
	b, err := os.ReadFile("testdata/rgb555_material_original.json")
	if err != nil {
		t.Fatal(err)
	}
	var oracle originalRGB555Oracle
	if err := json.Unmarshal(b, &oracle); err != nil {
		t.Fatal(err)
	}
	if oracle.Original != "0040e2c0683b4d73a5fb976e400d5087dca680df2b195c9e27f8edbda2d4974a" ||
		oracle.Mode.Index != 1 || oracle.Mode.Pack != 0x4351c0 || oracle.Mode.Unpack != 0x435280 ||
		oracle.Split.Count != 65536 || len(oracle.Materials) != 48 || len(oracle.RGBMaterials) != 36 ||
		len(oracle.MemoryFaults) != 0 || !oracle.Unchanged {
		t.Fatal("wrong original scalar RGB5551 transcript")
	}
	return oracle
}

// The digest is generated by executing every 16-bit input through the
// unchanged PE32 split function, using its own mode-1 initialization table.
// This checks scalar color behavior, not an original Windows framebuffer.
func TestSplitColor16MatchesOriginal435280(t *testing.T) {
	checkOriginalRGB555Split(t, func(word uint16) Color16 { return SplitColor16(word) })
}

func TestSplitTypedColorMatchesOriginal435280(t *testing.T) {
	checkOriginalRGB555Split(t, func(word uint16) Color16 { return SplitColor(noxcolor.RGBA5551(word)) })
}

func checkOriginalRGB555Split(t *testing.T, split func(uint16) Color16) {
	t.Helper()
	oracle := readOriginalRGB555Oracle(t)
	h := sha256.New()
	for word := 0; word < oracle.Split.Count; word++ {
		got := split(uint16(word))
		if got.R > 255 || got.G > 255 || got.B > 255 {
			t.Fatalf("word=%04x: original byte outputs cannot represent %+v", word, got)
		}
		_, _ = h.Write([]byte{byte(got.R), byte(got.G), byte(got.B)})
	}
	if got := fmt.Sprintf("%x", h.Sum(nil)); got != oracle.Split.RGBSHA256 {
		t.Fatalf("all 65536 original RGB outputs: got %s, want %s", got, oracle.Split.RGBSHA256)
	}
}

func TestRenderMaterialMatchesOriginal4341D0(t *testing.T) {
	oracle := readOriginalRGB555Oracle(t)
	for _, row := range oracle.Materials {
		d := originalMaterialData()
		want := *d
		if row.RGB != nil {
			want.materials[row.Index].Color = RGB{row.RGB[0], row.RGB[1], row.RGB[2]}
			want.materials[row.Index].Color32 = row.Color32
		}
		d.SetMaterial(row.Index, noxcolor.RGBA5551(uint16(row.Color32)))
		if *d != want {
			t.Fatalf("material %d, packed=%08x differs from original state or changed neighbors", row.Index, row.Color32)
		}
		d.SetMaterial(row.Index, noxcolor.RGBA5551(uint16(row.Color32)))
		if *d != want {
			t.Fatalf("material %d: original cached call must leave all state unchanged", row.Index)
		}
	}
}

func TestRenderMaterialRGBMatchesOriginal4340A0(t *testing.T) {
	oracle := readOriginalRGB555Oracle(t)
	for _, row := range oracle.RGBMaterials {
		d := originalMaterialData()
		want := *d
		if row.RGB != nil {
			want.materials[row.Index].Color = RGB{row.RGB[0], row.RGB[1], row.RGB[2]}
			want.materials[row.Index].Color32 = row.Color32
		}
		d.SetMaterialRGB(row.Index, row.Input[0], row.Input[1], row.Input[2])
		if *d != want {
			t.Fatalf("material %d, RGB=%v differs from original state or changed neighbors", row.Index, row.Input)
		}
	}
}

func originalMaterialData() *RenderData {
	d := newRenderData(7, 11)
	for i := range d.materials {
		d.materials[i] = RenderMat{
			field0: 0x11223344, field1: 0x55667788, field2: 0x99aabbcc,
			field3: 0xddeeff00, field4: 0x5a5a5a5a, field5: uint32(i),
			Color: RGB{90, 90, 90}, field9: 0xa5a5a5a5, Color32: 0x5a5a5a5a, field11: 0x12345678,
		}
	}
	return d
}
